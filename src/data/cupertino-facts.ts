export const CUPERTINO_FACT_COUNT = CUPERTINO_FACTS.length;

export function shuffleCupertinoFacts(
  facts: readonly CupertinoFact[] = CUPERTINO_FACTS,
  previousFactId?: string,
): CupertinoFact[] {
  const shuffled = [...facts];

  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [shuffled[index], shuffled[randomIndex]] = [shuffled[randomIndex], shuffled[index]];
  }

  if (
    previousFactId &&
    shuffled.length > 1 &&
    shuffled[0]?.id === previousFactId
  ) {
    [shuffled[0], shuffled[1]] = [shuffled[1], shuffled[0]];
  }

  return shuffled;
}

export function validateCupertinoFacts(): void {
  const ids = new Set<string>();
  const texts = new Set<string>();

  for (const fact of CUPERTINO_FACTS) {
    if (ids.has(fact.id)) throw new Error(`Duplicate Cupertino fact id: ${fact.id}`);
    if (texts.has(fact.text)) throw new Error(`Duplicate Cupertino fact text: ${fact.text}`);
    ids.add(fact.id);
    texts.add(fact.text);
  }
}
